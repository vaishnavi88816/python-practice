import numpy as np

# Create two arrays
a = np.array([1, 2, 3])
b = np.array([4, 5, 6])

# Addition
sum_array = a + b

# Multiplication
mul_array = a * b

# Mean of array a
mean_a = np.mean(a)

print("Array a:", a)
print("Array b:", b)
print("Addition:", sum_array)
print("Multiplication:", mul_array)
print("Mean of a:", mean_a)